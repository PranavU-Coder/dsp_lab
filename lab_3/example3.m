clc; close all;
x1 = [1 2 3 4 5 6 7 8];
x2 = [1 1 1 1];
N1 = length(x1);
N2 = length(x2);
N = max(N1,N2);
y = cconv(x1,x2,N);
X1 = fft(x1,N);
X2 = fft(x2,N);
Y = X1.*X2;
z = ifft(Y,N);
display(y); display(z);
yy = conv(x1,x2);
N = length(yy);
X1 = fft(x1,N);
X2 = fft(x2,N);
Y = X1.*X2;
zz = ifft(Y,N);
display(yy); display(zz);
