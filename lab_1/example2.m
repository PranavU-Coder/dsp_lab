clc; close all;
Fs = 1000;
f = 200;
t = 0:1/Fs:(1/f);
x = 5*sin(2*pi*f*t);
subplot(3,1,1); stem(t,x);
title('sine wave sampled at 1000Hz, one period duration');
ylabel('amplitude'); xlabel('time');
Fs1 = 10000;
t = 0:1/Fs1:(1/f);
x1 = 5*sin(2*pi*f*t);
subplot(3,1,2); stem(t,x1);
title('sine wave sampled at 10000Hz, one period duration');
ylabel('amplitude'); xlabel('time');
t = 0:1/Fs1:(2/f);
x2 = 5*sin(2*pi*f*t);
subplot(3,1,3); stem(t,x2);
title('sine wave sampled at 10000Hz, two cycle duration');
ylabel('amplitude'); xlabel('time');
